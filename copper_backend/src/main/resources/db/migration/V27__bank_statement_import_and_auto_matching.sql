CREATE TABLE bank_statement_import_batch (
  id bigint unsigned NOT NULL AUTO_INCREMENT,
  session_id bigint unsigned NOT NULL,
  batch_no varchar(64) NOT NULL,
  template_version varchar(64) NOT NULL,
  source_file_name varchar(255) NOT NULL,
  source_file_format varchar(16) NOT NULL COMMENT 'CSV, XLSX',
  source_file_sha256 char(64) NOT NULL,
  source_file_size bigint unsigned NOT NULL,
  source_storage_path varchar(1000) NOT NULL,
  status varchar(24) NOT NULL DEFAULT 'PREVIEWED' COMMENT 'PREVIEWED, COMPLETED, CANCELLED',
  total_rows int unsigned NOT NULL DEFAULT 0,
  valid_rows int unsigned NOT NULL DEFAULT 0,
  duplicate_rows int unsigned NOT NULL DEFAULT 0,
  error_rows int unsigned NOT NULL DEFAULT 0,
  auto_match_rows int unsigned NOT NULL DEFAULT 0,
  review_rows int unsigned NOT NULL DEFAULT 0,
  unmatched_rows int unsigned NOT NULL DEFAULT 0,
  imported_rows int unsigned NOT NULL DEFAULT 0,
  applied_auto_match_rows int unsigned NOT NULL DEFAULT 0,
  imported_by bigint unsigned NOT NULL DEFAULT 0,
  imported_by_name varchar(128) NOT NULL DEFAULT '',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at timestamp NULL DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_bank_statement_import_batch_no (batch_no),
  KEY idx_bank_statement_import_session (session_id,status,id),
  KEY idx_bank_statement_import_file (session_id,source_file_sha256,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='银行流水文件导入批次、原文件证据及处理汇总';

CREATE TABLE bank_statement_import_row (
  id bigint unsigned NOT NULL AUTO_INCREMENT,
  batch_id bigint unsigned NOT NULL,
  source_row_no int unsigned NOT NULL,
  transaction_date date NULL,
  value_date date NULL,
  bank_serial_no varchar(128) NOT NULL DEFAULT '',
  direction varchar(8) NOT NULL DEFAULT '',
  amount decimal(18,2) NULL,
  balance decimal(18,2) NULL,
  counterparty_name varchar(255) NOT NULL DEFAULT '',
  counterparty_account varchar(128) NOT NULL DEFAULT '',
  purpose varchar(500) NOT NULL DEFAULT '',
  source_hash char(64) NOT NULL DEFAULT '',
  validation_status varchar(16) NOT NULL COMMENT 'VALID, DUPLICATE, ERROR',
  validation_message varchar(500) NOT NULL DEFAULT '',
  duplicate_type varchar(32) NOT NULL DEFAULT 'NONE' COMMENT 'NONE, FILE_EXACT, FILE_SERIAL, EXISTING_EXACT, EXISTING_SERIAL',
  duplicate_statement_line_id bigint unsigned NOT NULL DEFAULT 0,
  match_action varchar(24) NOT NULL DEFAULT 'UNMATCHED' COMMENT 'AUTO_MATCH, REVIEW, UNMATCHED, DUPLICATE, INVALID',
  suggested_source_type varchar(32) NOT NULL DEFAULT '',
  suggested_source_id bigint unsigned NOT NULL DEFAULT 0,
  suggested_source_no varchar(64) NOT NULL DEFAULT '',
  suggested_score int unsigned NOT NULL DEFAULT 0,
  suggested_reason varchar(500) NOT NULL DEFAULT '',
  unmatched_reason_code varchar(48) NOT NULL DEFAULT '',
  unmatched_reason varchar(500) NOT NULL DEFAULT '',
  imported_statement_line_id bigint unsigned NOT NULL DEFAULT 0,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_bank_statement_import_row (batch_id,source_row_no),
  KEY idx_bank_statement_import_row_status (batch_id,validation_status,match_action,source_row_no),
  KEY idx_bank_statement_import_row_hash (batch_id,source_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='银行流水导入逐行校验、重复依据、匹配建议和未匹配原因';

