CREATE TABLE treasury_document (
  id bigint unsigned NOT NULL AUTO_INCREMENT,
  document_no varchar(64) NOT NULL,
  document_type varchar(32) NOT NULL COMMENT 'CORPORATE_EXPENSE, OTHER_EXPENSE, OTHER_INCOME, OTHER_RECEIVABLE, OTHER_PAYABLE',
  partner_id bigint unsigned NOT NULL,
  partner_name_snapshot varchar(255) NOT NULL,
  business_date date NOT NULL,
  due_date date NOT NULL,
  basis_no varchar(128) NOT NULL,
  summary varchar(255) NOT NULL,
  offset_account_id bigint unsigned NOT NULL,
  offset_account_code_snapshot varchar(32) NOT NULL,
  offset_account_name_snapshot varchar(128) NOT NULL,
  price_includes_tax tinyint unsigned NOT NULL DEFAULT 1,
  tax_rate decimal(8,4) NOT NULL DEFAULT 0.0000,
  amount_excluding_tax decimal(18,2) NOT NULL,
  tax_amount decimal(18,2) NOT NULL DEFAULT 0.00,
  total_amount decimal(18,2) NOT NULL,
  tax_rounding_difference decimal(18,2) NOT NULL DEFAULT 0.00,
  tax_rule_snapshot varchar(1000) NOT NULL DEFAULT '',
  settled_amount decimal(18,2) NOT NULL DEFAULT 0.00,
  status varchar(24) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT, CONFIRMED, PARTIALLY_SETTLED, SETTLED, CANCELLED, REVERSED',
  accounting_voucher_id bigint unsigned NOT NULL DEFAULT 0,
  version_no int unsigned NOT NULL DEFAULT 1,
  memo varchar(500) NOT NULL DEFAULT '',
  created_by bigint unsigned NOT NULL DEFAULT 0,
  created_by_name varchar(128) NOT NULL DEFAULT '',
  confirmed_by bigint unsigned NOT NULL DEFAULT 0,
  confirmed_by_name varchar(128) NOT NULL DEFAULT '',
  confirmed_at timestamp NULL DEFAULT NULL,
  cancelled_by bigint unsigned NOT NULL DEFAULT 0,
  cancelled_by_name varchar(128) NOT NULL DEFAULT '',
  cancel_reason varchar(500) NOT NULL DEFAULT '',
  cancelled_at timestamp NULL DEFAULT NULL,
  reversed_by bigint unsigned NOT NULL DEFAULT 0,
  reversed_by_name varchar(128) NOT NULL DEFAULT '',
  reversal_reason varchar(500) NOT NULL DEFAULT '',
  reversed_at timestamp NULL DEFAULT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_treasury_document_no (document_no),
  KEY idx_treasury_document_partner (partner_id,business_date,id),
  KEY idx_treasury_document_status (status,business_date,id),
  KEY idx_treasury_document_due (status,due_date,id),
  CONSTRAINT chk_treasury_document_amount CHECK (total_amount > 0 AND amount_excluding_tax >= 0 AND tax_amount >= 0),
  CONSTRAINT chk_treasury_document_tax CHECK (amount_excluding_tax + tax_amount = total_amount),
  CONSTRAINT chk_treasury_document_settled CHECK (settled_amount >= 0 AND settled_amount <= total_amount),
  CONSTRAINT chk_treasury_document_type CHECK (document_type IN ('CORPORATE_EXPENSE','OTHER_EXPENSE','OTHER_INCOME','OTHER_RECEIVABLE','OTHER_PAYABLE')),
  CONSTRAINT chk_treasury_document_status CHECK (status IN ('DRAFT','CONFIRMED','PARTIALLY_SETTLED','SETTLED','CANCELLED','REVERSED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='ERP-05 对公费用、其他收支及其他往来源单；资金、发票和凭证分层';

CREATE TABLE treasury_document_event (
  id bigint unsigned NOT NULL AUTO_INCREMENT,
  document_id bigint unsigned NOT NULL,
  action varchar(32) NOT NULL,
  from_status varchar(24) NOT NULL DEFAULT '',
  to_status varchar(24) NOT NULL DEFAULT '',
  reason varchar(500) NOT NULL DEFAULT '',
  operator_id bigint unsigned NOT NULL DEFAULT 0,
  operator_name varchar(128) NOT NULL DEFAULT '',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_treasury_document_event (document_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='费用及其他往来源单不可变状态事件';

CREATE TABLE treasury_payment_request (
  id bigint unsigned NOT NULL AUTO_INCREMENT,
  request_no varchar(64) NOT NULL,
  document_id bigint unsigned NOT NULL,
  requested_amount decimal(18,2) NOT NULL,
  paid_amount decimal(18,2) NOT NULL DEFAULT 0.00,
  request_date date NOT NULL,
  expected_payment_date date NOT NULL,
  purpose varchar(500) NOT NULL,
  status varchar(24) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT, APPROVED, PARTIALLY_PAID, PAID, REJECTED, CANCELLED',
  version_no int unsigned NOT NULL DEFAULT 1,
  created_by bigint unsigned NOT NULL DEFAULT 0,
  created_by_name varchar(128) NOT NULL DEFAULT '',
  approved_by bigint unsigned NOT NULL DEFAULT 0,
  approved_by_name varchar(128) NOT NULL DEFAULT '',
  approved_at timestamp NULL DEFAULT NULL,
  rejected_by bigint unsigned NOT NULL DEFAULT 0,
  rejected_by_name varchar(128) NOT NULL DEFAULT '',
  rejected_reason varchar(500) NOT NULL DEFAULT '',
  rejected_at timestamp NULL DEFAULT NULL,
  cancelled_by bigint unsigned NOT NULL DEFAULT 0,
  cancelled_by_name varchar(128) NOT NULL DEFAULT '',
  cancel_reason varchar(500) NOT NULL DEFAULT '',
  cancelled_at timestamp NULL DEFAULT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_treasury_payment_request_no (request_no),
  KEY idx_treasury_payment_request_document (document_id,status,id),
  KEY idx_treasury_payment_request_status (status,expected_payment_date,id),
  CONSTRAINT chk_treasury_payment_request_amount CHECK (requested_amount > 0 AND paid_amount >= 0 AND paid_amount <= requested_amount),
  CONSTRAINT chk_treasury_payment_request_status CHECK (status IN ('DRAFT','APPROVED','PARTIALLY_PAID','PAID','REJECTED','CANCELLED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='ERP-05 可选付款申请；审批不等于付款';

CREATE TABLE treasury_payment_request_event (
  id bigint unsigned NOT NULL AUTO_INCREMENT,
  request_id bigint unsigned NOT NULL,
  action varchar(32) NOT NULL,
  from_status varchar(24) NOT NULL DEFAULT '',
  to_status varchar(24) NOT NULL DEFAULT '',
  reason varchar(500) NOT NULL DEFAULT '',
  operator_id bigint unsigned NOT NULL DEFAULT 0,
  operator_name varchar(128) NOT NULL DEFAULT '',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_treasury_payment_request_event (request_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='付款申请审批、退回及支付进度审计';

CREATE TABLE treasury_fund_transaction (
  id bigint unsigned NOT NULL AUTO_INCREMENT,
  fund_no varchar(64) NOT NULL,
  fund_type varchar(24) NOT NULL COMMENT 'DOCUMENT_SETTLEMENT, INTERNAL_TRANSFER',
  document_id bigint unsigned NOT NULL DEFAULT 0,
  payment_request_id bigint unsigned NOT NULL DEFAULT 0,
  direction varchar(16) NOT NULL COMMENT 'CREDIT, DEBIT, TRANSFER',
  settlement_method varchar(16) NOT NULL COMMENT 'CASH, BANK',
  business_bank_account_id bigint unsigned NOT NULL DEFAULT 0,
  counter_bank_account_id bigint unsigned NOT NULL DEFAULT 0,
  amount decimal(18,2) NOT NULL,
  transaction_date date NOT NULL,
  cash_flow_category varchar(48) NOT NULL,
  counterparty_name_snapshot varchar(255) NOT NULL DEFAULT '',
  purpose varchar(500) NOT NULL,
  status varchar(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE, REVERSED',
  accounting_voucher_id bigint unsigned NOT NULL DEFAULT 0,
  reversal_voucher_id bigint unsigned NOT NULL DEFAULT 0,
  created_by bigint unsigned NOT NULL DEFAULT 0,
  created_by_name varchar(128) NOT NULL DEFAULT '',
  reversed_by bigint unsigned NOT NULL DEFAULT 0,
  reversed_by_name varchar(128) NOT NULL DEFAULT '',
  reversal_reason varchar(500) NOT NULL DEFAULT '',
  reversed_at timestamp NULL DEFAULT NULL,
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_treasury_fund_no (fund_no),
  KEY idx_treasury_fund_document (document_id,status,transaction_date,id),
  KEY idx_treasury_fund_request (payment_request_id,status,id),
  KEY idx_treasury_fund_date (status,transaction_date,id),
  CONSTRAINT chk_treasury_fund_amount CHECK (amount > 0),
  CONSTRAINT chk_treasury_fund_type CHECK (fund_type IN ('DOCUMENT_SETTLEMENT','INTERNAL_TRANSFER')),
  CONSTRAINT chk_treasury_fund_direction CHECK (direction IN ('CREDIT','DEBIT','TRANSFER')),
  CONSTRAINT chk_treasury_fund_status CHECK (status IN ('ACTIVE','REVERSED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='ERP-05 实际资金事项；付款申请、费用源单与资金分层';

CREATE TABLE treasury_cash_journal (
  id bigint unsigned NOT NULL AUTO_INCREMENT,
  journal_no varchar(64) NOT NULL,
  fund_transaction_id bigint unsigned NOT NULL,
  line_no tinyint unsigned NOT NULL,
  source_type varchar(32) NOT NULL DEFAULT 'TREASURY_FUND',
  source_id bigint unsigned NOT NULL,
  source_no varchar(64) NOT NULL,
  transaction_date date NOT NULL,
  business_bank_account_id bigint unsigned NOT NULL DEFAULT 0,
  settlement_method varchar(16) NOT NULL,
  direction varchar(8) NOT NULL COMMENT 'CREDIT 收入, DEBIT 支出',
  amount decimal(18,2) NOT NULL,
  cash_flow_category varchar(48) NOT NULL,
  partner_id bigint unsigned NOT NULL DEFAULT 0,
  partner_name_snapshot varchar(255) NOT NULL DEFAULT '',
  purpose varchar(500) NOT NULL,
  status varchar(16) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE, REVERSED',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reversed_at timestamp NULL DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_treasury_cash_journal_no (journal_no),
  UNIQUE KEY uk_treasury_cash_journal_line (fund_transaction_id,line_no),
  KEY idx_treasury_cash_journal_bank (business_bank_account_id,status,transaction_date,id),
  KEY idx_treasury_cash_journal_source (source_type,source_id,status,id),
  CONSTRAINT chk_treasury_cash_journal_amount CHECK (amount > 0),
  CONSTRAINT chk_treasury_cash_journal_direction CHECK (direction IN ('CREDIT','DEBIT')),
  CONSTRAINT chk_treasury_cash_journal_status CHECK (status IN ('ACTIVE','REVERSED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='ERP-05 可逐笔对账的出纳日记账增量事实';

CREATE TABLE treasury_fund_event (
